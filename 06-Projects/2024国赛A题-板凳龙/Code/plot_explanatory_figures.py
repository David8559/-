def plot_q1_explainer() -> None:
    fig, axes = plt.subplots(1, 2, figsize=(7.1, 3.0))

    ax = axes[0]
    panel_title(ax, "a", "固定弦长方程为何要选“最近根”")
    b = 0.11
    theta = np.linspace(7.0, 28.0, 1200)
    xy = np.column_stack((b * theta * np.cos(theta), b * theta * np.sin(theta)))
    ax.plot(xy[:, 0], xy[:, 1], color=BLUE)
    k = 430
    p_prev = xy[k]
    distances = np.linalg.norm(xy - p_prev, axis=1)
    d = 1.20
    crossings = np.where(np.diff(np.sign(distances - d)) != 0)[0]
    candidates = [idx for idx in crossings if idx > k + 5]
    ax.add_patch(Circle(p_prev, d, fill=False, color=VERMILION, linestyle="--"))
    ax.plot(*p_prev, "o", color=BLACK, markersize=5)
    ax.text(*(p_prev + np.array([0.10, 0.10])), "$P_{i-1}$")
    if candidates:
        nearest = candidates[0]
        ax.plot(*xy[nearest], "o", color=GREEN, markersize=6)
        ax.annotate(
            "沿链方向的第一个交点\n（采用的最近根）",
            xy=xy[nearest],
            xytext=(-2.7, -1.95),
            arrowprops={"arrowstyle": "->", "color": GREEN},
            color=GREEN,
        )
        for idx in candidates[1:3]:
            ax.plot(*xy[idx], "x", color=PURPLE, markersize=6)
    ax.text(-2.9, 2.25, "$\\|P_i-P_{i-1}\\|=d_i$", color=VERMILION)
    ax.set_aspect("equal")
    ax.set_xlim(-3.1, 3.1)
    ax.set_ylim(-2.35, 2.55)
    ax.axis("off")

    ax = axes[1]
    panel_title(ax, "b", "刚性约束把前一把手速度投影到后一把手")
    p0 = np.array([-1.7, -0.45])
    p1 = np.array([1.55, 0.50])
    chord = p1 - p0
    chord /= np.linalg.norm(chord)
    t0 = np.array([0.38, 0.93])
    t1 = np.array([0.82, 0.57])
    ax.plot([p0[0], p1[0]], [p0[1], p1[1]], color=BLACK, linewidth=2.4)
    ax.plot(*p0, "o", color=BLUE, markersize=6)
    ax.plot(*p1, "o", color=GREEN, markersize=6)
    ax.text(*(p0 + np.array([-0.25, -0.28])), "$P_{i-1}$", color=BLUE)
    ax.text(*(p1 + np.array([0.06, -0.28])), "$P_i$", color=GREEN)
    for p, tangent, color, label in (
        (p0, t0, BLUE, "$v_{i-1}$"),
        (p1, t1, GREEN, "$v_i$"),
    ):
        ax.add_patch(
            FancyArrowPatch(
                p,
                p + 1.25 * tangent,
                arrowstyle="-|>",
                mutation_scale=12,
                color=color,
                linewidth=1.8,
            )
        )
        ax.plot(
            [p[0] - tangent[0], p[0] + tangent[0]],
            [p[1] - tangent[1], p[1] + tangent[1]],
            color=color,
            linestyle=":",
            linewidth=1.0,
        )
        ax.text(*(p + 1.35 * tangent), label, color=color)
    ax.add_patch(
        FancyArrowPatch(
            p0,
            p0 + 1.2 * chord,
            arrowstyle="-|>",
            mutation_scale=10,
            color=VERMILION,
            linestyle="--",
        )
    )
    ax.add_patch(
        FancyArrowPatch(
            p1,
            p1 - 1.2 * chord,
            arrowstyle="-|>",
            mutation_scale=10,
            color=VERMILION,
            linestyle="--",
        )
    )
    ax.text(
        0,
        -1.42,
        "沿板凳轴向的相对速度必须为 0\n"
        "$(P_i-P_{i-1})^T(v_i-v_{i-1})=0$",
        ha="center",
        color=VERMILION,
    )
    ax.set_aspect("equal")
    ax.set_xlim(-2.25, 2.35)
    ax.set_ylim(-1.65, 2.05)
    ax.axis("off")

    fig.tight_layout(w_pad=1.4)
    finish(fig, "q1_fixed_chord_velocity_explainer")


