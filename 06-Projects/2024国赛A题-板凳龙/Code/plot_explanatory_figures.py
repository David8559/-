def panel_title(ax: plt.Axes, letter: str, title: str) -> None:
    ax.set_title(f"({letter}) {title}", loc="left", fontweight="bold", pad=5)


def draw_dimension(
    ax: plt.Axes,
    start: tuple[float, float],
    end: tuple[float, float],
    text: str,
    *,
    color: str = BLACK,
) -> None:
    ax.annotate(
        "",
        xy=end,
        xytext=start,
        arrowprops={
            "arrowstyle": "<->",
            "color": color,
            "linewidth": 0.9,
            "shrinkA": 0,
            "shrinkB": 0,
        },
    )
    ax.text(
        0.5 * (start[0] + end[0]),
        0.5 * (start[1] + end[1]) + 0.08,
        text,
        ha="center",
        va="bottom",
        color=color,
    )


def rotated_rectangle(
    center: tuple[float, float],
    length: float,
    width: float,
    angle: float,
) -> np.ndarray:
    corners = np.array(
        [
            [-length / 2, -width / 2],
            [length / 2, -width / 2],
            [length / 2, width / 2],
            [-length / 2, width / 2],
        ]
    )
    rotation = np.array(
        [[np.cos(angle), -np.sin(angle)], [np.sin(angle), np.cos(angle)]]
    )
    return corners @ rotation.T + np.asarray(center)


